import fs from "node:fs";
import path from "node:path";
import StyleDictionary from "style-dictionary";
import type { TransformedToken } from "style-dictionary/types";
import { checkContrast, CONTRAST_PAIRS, formatContrastFailure, type Oklch } from "./src/contrast";
import { readTokens, TYPOGRAPHY_PARTS, walk } from "./src/dtcg";

/**
 * Builds the tokens (TOK-001). DTCG JSON in src/ becomes
 *   dist/tokens.css   custom properties, all prefixed --kan- (TOK-002): light on :root, dark under
 *                     [data-theme="dark"] and prefers-color-scheme (TOK-003), semantic ones written
 *                     as var() of what they reference (TOK-004), durations at 0ms for reduced motion
 *   dist/tokens.ts    every token name as a string literal type (TOK-005)
 *   dist/tokens.json  every token for the docs, with its light and dark values and references
 *
 * src/primitive/ holds raw values. src/semantic/base.json holds roles that don't change with the
 * mode; light.json and dark.json hold the color roles for each mode and must define the same names
 * (SEM-002). The build fails on a broken reference (TOK-006) or a contrast pair below WCAG AA
 * (TOK-007). Output has no timestamps, so the same source builds the same bytes (TOK-008).
 *
 *   bun run build                      src/ → dist/
 *   bun run build --src <dir> --out <dir>
 */

const PREFIX = "kan";
const HEADER = "Generated by packages/tokens/build.ts from packages/tokens/src. Do not edit.";
const MODES = ["light", "dark"] as const;
type Mode = (typeof MODES)[number];
const GENERIC_FONTS = new Set([
  "serif",
  "sans-serif",
  "monospace",
  "cursive",
  "fantasy",
  "system-ui",
  "ui-serif",
  "ui-sans-serif",
  "ui-monospace",
  "ui-rounded",
  "-apple-system",
]);
const PART_NAMES = {
  fontFamily: "font-family",
  fontSize: "font-size",
  fontWeight: "font-weight",
  lineHeight: "line-height",
} as const;

type Dimension = { value: number; unit: string };
const round = (n: number) => Number(n.toFixed(4));

/** CSS for a DTCG value of `type`. `rem` turns px into rem (font sizes). */
function cssValue(type: string, value: unknown, rem = false): string {
  switch (type) {
    case "color": {
      const { colorSpace, components, alpha } = value as { colorSpace: string; components: number[]; alpha?: number };
      if (colorSpace !== "oklch") throw new Error(`only oklch colors are supported, got ${colorSpace}`);
      return `oklch(${components.join(" ")}${alpha !== undefined && alpha !== 1 ? ` / ${alpha}` : ""})`;
    }
    case "dimension": {
      const { value: v, unit } = value as Dimension;
      return unit === "px" && rem ? `${round(v / 16)}rem` : `${v}${unit}`;
    }
    case "duration":
      return `${(value as Dimension).value}${(value as Dimension).unit}`;
    case "cubicBezier":
      return `cubic-bezier(${(value as number[]).join(", ")})`;
    case "fontFamily":
      return ([] as string[])
        .concat(value as string | string[])
        .map((f) => (GENERIC_FONTS.has(f) || /^[\w-]+$/.test(f) ? f : `"${f}"`))
        .join(", ");
    default:
      return String(value);
  }
}

const isFontSize = (p: string[]) => p[0] === "font" && p[1] === "size";
const transforms = {
  "kan/value": {
    type: "value" as const,
    filter: (t: TransformedToken) => t.$type !== "typography",
    transform: (t: TransformedToken) => cssValue(t.$type!, t.$value, isFontSize(t.path)),
  },
};

/** One custom property: its value in light, its value in dark if that differs, and what it references. */
export type Row = {
  name: string;
  cssVar: string;
  type: string;
  layer: "primitive" | "semantic";
  value: string;
  ref?: string;
  dark?: string;
  darkRef?: string;
  group?: string;
  description?: string;
};

const refOf = (v: unknown) => (typeof v === "string" ? /^\{([^{}]+)\}$/.exec(v)?.[1] : undefined);
const dotted = (t: TransformedToken) => t.path.join(".");

/** Every token as Style Dictionary resolves it for one mode. */
async function resolveMode(src: string, mode: Mode): Promise<TransformedToken[]> {
  const semantic = path.join(src, "semantic");
  const others = fs.existsSync(semantic)
    ? fs
        .readdirSync(semantic)
        .filter((f) => f.endsWith(".json") && !["base.json", "light.json", "dark.json"].includes(f))
        .sort()
    : [];
  const source = [
    path.join(src, "primitive/**/*.json"),
    path.join(semantic, "base.json"),
    path.join(semantic, `${mode}.json`),
    ...others.map((f) => path.join(semantic, f)),
  ].filter((f) => f.includes("*") || fs.existsSync(f));
  const sd = new StyleDictionary({
    source,
    usesDtcg: true,
    log: { verbosity: "verbose", warnings: "disabled", errors: { brokenReferences: "throw" } },
    hooks: { transforms },
    platforms: { web: { transforms: ["name/kebab", ...Object.keys(transforms)], prefix: PREFIX } },
  });
  try {
    return (await sd.getPlatformTokens("web")).allTokens;
  } catch (e) {
    const refs = [
      ...(e as Error).message.matchAll(/\{([^}]+)\} tries to reference \{([^}]+)\}, which is not defined/g),
    ];
    if (!refs.length) throw e;
    const lines = [...new Set(refs.map(([, from, to]) => `  ${from} references ${to}, which doesn't exist`))];
    throw new Error(`broken references:\n${lines.join("\n")}`, { cause: e });
  }
}

/** Names that light.json and dark.json don't share (SEM-002). */
function modeMismatch(src: string): string[] {
  const names = (mode: Mode) => {
    const file = path.join(src, "semantic", `${mode}.json`);
    if (!fs.existsSync(file)) return new Set<string>();
    return new Set(walk(JSON.parse(fs.readFileSync(file, "utf8")), `${mode}.json`).tokens.map((t) => t.path.join(".")));
  };
  const [light, dark] = [names("light"), names("dark")];
  return [
    ...[...light].filter((n) => !dark.has(n)).map((n) => `${n} is only in light.json`),
    ...[...dark].filter((n) => !light.has(n)).map((n) => `${n} is only in dark.json`),
  ];
}

/** Every custom property, with typography tokens split into one property per part. */
function toRows(light: TransformedToken[], dark: TransformedToken[]): Row[] {
  const valueOf = (mode: TransformedToken[]) => new Map(mode.map((t) => [dotted(t), t]));
  const darkTokens = valueOf(dark);
  const rows: Row[] = [];
  for (const t of light) {
    const layer = t.filePath.includes(`${path.sep}semantic${path.sep}`) ? "semantic" : "primitive";
    const base = { layer, ...(t.$description ? { description: t.$description } : {}) } as const;
    if (t.$type === "typography") {
      const original = t.original.$value as Record<string, unknown>;
      for (const [part, partType] of Object.entries(TYPOGRAPHY_PARTS)) {
        const ref = refOf(original[part]);
        const target = ref ? valueOf(light).get(ref) : undefined;
        rows.push({
          ...base,
          name: `${dotted(t)}.${PART_NAMES[part as keyof typeof PART_NAMES]}`,
          cssVar: `--${t.name}-${PART_NAMES[part as keyof typeof PART_NAMES]}`,
          type: partType,
          value: target ? String(target.$value) : cssValue(partType, original[part], partType === "dimension"),
          ...(ref ? { ref } : {}),
          group: dotted(t),
        });
      }
      continue;
    }
    const ref = refOf(t.original.$value);
    const d = darkTokens.get(dotted(t));
    const darkRef = d ? refOf(d.original.$value) : undefined;
    const differs = d && (d.$value !== t.$value || darkRef !== ref);
    rows.push({
      ...base,
      name: dotted(t),
      cssVar: `--${t.name}`,
      type: t.$type!,
      value: String(t.$value),
      ...(ref ? { ref } : {}),
      ...(differs ? { dark: String(d.$value), ...(darkRef ? { darkRef } : {}) } : {}),
    });
  }
  return rows;
}

const declaration = (cssVarName: string, value: string, comment?: string) =>
  `  ${cssVarName}: ${value};${comment ? ` /** ${comment} */` : ""}`;

function css(rows: Row[]): string {
  const varOf = new Map(rows.map((r) => [r.name, r.cssVar]));
  const v = (ref: string | undefined, value: string) => (ref && varOf.has(ref) ? `var(${varOf.get(ref)})` : value);
  // A role that references another role follows it through var(), so it only needs a dark override when its reference changes.
  const darkRows = rows.filter((r) => r.dark !== undefined && (!r.ref || r.darkRef !== r.ref));
  const darkBody = darkRows.map((r) => declaration(r.cssVar, v(r.darkRef, r.dark!)));
  const motion = rows.filter((r) => r.layer === "semantic" && r.name.startsWith("motion.duration."));
  return [
    `/**\n * ${HEADER}\n */`,
    "",
    ":root {",
    ...rows.map((r) => declaration(r.cssVar, v(r.ref, r.value), r.description)),
    "}",
    "",
    '[data-theme="dark"] {',
    ...darkBody,
    "}",
    "",
    "@media (prefers-color-scheme: dark) {",
    '  :root:not([data-theme="light"]) {',
    ...darkBody.map((l) => `  ${l}`),
    "  }",
    "}",
    "",
    "@media (prefers-reduced-motion: reduce) {",
    "  :root {",
    ...motion.map((r) => `  ${declaration(r.cssVar, "0ms")}`),
    "  }",
    "}",
    "",
  ].join("\n");
}

function typedModule(rows: Row[]): string {
  const entry = (r: Row) =>
    `  ${JSON.stringify(r.name)}: { cssVar: ${JSON.stringify(r.cssVar)}, type: ${JSON.stringify(r.type)}, value: ${JSON.stringify(r.value)}${r.dark !== undefined ? `, dark: ${JSON.stringify(r.dark)}` : ""} },`;
  return [
    `// ${HEADER}`,
    "",
    "export const tokens = {",
    ...rows.map(entry),
    "} as const;",
    "",
    '/** Every token\'s name, e.g. "color.cyan.500" or "color.text.default". */',
    "export type TokenName = keyof typeof tokens;",
    "",
    "/** var(--kan-…) for a token, for inline styles and CSS-in-JS. It follows the current theme. */",
    "export const cssVar = (name: TokenName): string => `var(${tokens[name].cssVar})`;",
    "",
  ].join("\n");
}

const parseOklch = (value: string): Oklch => {
  const m = /^oklch\(([\d.]+) ([\d.]+) ([\d.]+)/.exec(value);
  if (!m) throw new Error(`not an oklch color: ${value}`);
  return [Number(m[1]), Number(m[2]), Number(m[3])];
};

export type BuildResult = { files: string[]; rows: Row[]; contrastChecked: number };

/** Resolves every token in both modes and checks them, without writing anything. */
export async function resolveTokens(src: string): Promise<{ rows: Row[]; contrastChecked: number }> {
  const { problems } = readTokens(src);
  if (problems.length) throw new Error(`invalid tokens:\n${problems.map((p) => `  ${p}`).join("\n")}`);
  const mismatch = modeMismatch(src);
  if (mismatch.length) {
    throw new Error(`light and dark must define the same tokens:\n${mismatch.map((m) => `  ${m}`).join("\n")}`);
  }
  const [light, dark] = [await resolveMode(src, "light"), await resolveMode(src, "dark")];
  const rows = toRows(light, dark);

  const hasSemanticColors = rows.some((r) => r.name === "color.bg.canvas");
  let contrastChecked = 0;
  if (hasSemanticColors) {
    const byName = new Map(rows.map((r) => [r.name, r]));
    const color = (name: string, mode: string) => {
      const r = byName.get(name);
      if (!r) throw new Error(`contrast: ${name} doesn't exist`);
      return parseOklch(mode === "dark" && r.dark !== undefined ? r.dark : r.value);
    };
    const failures = checkContrast([...MODES], color);
    contrastChecked = CONTRAST_PAIRS.length * MODES.length;
    if (failures.length)
      throw new Error(`contrast:\n${failures.map((f) => `  ${formatContrastFailure(f)}`).join("\n")}`);
  }
  return { rows, contrastChecked };
}

export async function buildTokens({ src, out }: { src: string; out: string }): Promise<BuildResult> {
  const { rows, contrastChecked } = await resolveTokens(src);
  fs.mkdirSync(out, { recursive: true });
  const files: [string, string][] = [
    ["tokens.css", css(rows)],
    ["tokens.ts", typedModule(rows)],
    ["tokens.json", `${JSON.stringify(rows, null, 2)}\n`],
  ];
  for (const [file, text] of files) fs.writeFileSync(path.join(out, file), text);
  return { files: files.map(([f]) => path.join(out, f)), rows, contrastChecked };
}

if (import.meta.main) {
  const arg = (name: string, fallback: string) => {
    const i = process.argv.indexOf(name);
    return path.resolve(i > 0 ? process.argv[i + 1] : fallback);
  };
  try {
    const { files, rows, contrastChecked } = await buildTokens({
      src: arg("--src", path.join(import.meta.dir, "src")),
      out: arg("--out", path.join(import.meta.dir, "dist")),
    });
    console.log(
      `built ${files.map((f) => path.relative(process.cwd(), f)).join(", ")} · ${rows.length} properties · ${contrastChecked} contrast pairs pass`,
    );
  } catch (e) {
    console.error(`tokens: ${(e as Error).message}`);
    process.exit(1);
  }
}
