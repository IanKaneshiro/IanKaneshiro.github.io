import fs from "node:fs";
import path from "node:path";
import StyleDictionary from "style-dictionary";
import type { TransformedToken } from "style-dictionary/types";
import { readTokens } from "./src/dtcg";

/**
 * Builds the tokens (TOK-001): DTCG JSON in src/ becomes
 *   dist/tokens.css   CSS custom properties, all prefixed --kan- (TOK-002)
 *   dist/tokens.ts    every token name as a string literal type (TOK-005)
 *   dist/tokens.json  name, CSS variable, type, value and description of each token, for the docs
 *
 * The output has no timestamps, so the same source always builds the same bytes (TOK-008).
 * A reference to a token that doesn't exist fails the build, naming both (TOK-006).
 *
 *   bun run build                      src/ → dist/
 *   bun run build --src <dir> --out <dir>
 */

const PREFIX = "kan";
const HEADER = "Generated by packages/tokens/build.ts from packages/tokens/src. Do not edit.";
const GENERIC_FONTS = new Set([
  "serif",
  "sans-serif",
  "monospace",
  "cursive",
  "fantasy",
  "system-ui",
  "ui-serif",
  "ui-sans-serif",
  "ui-monospace",
  "ui-rounded",
  "-apple-system",
]);

type Dimension = { value: number; unit: string };
const isRem = (t: TransformedToken) => t.path[0] === "font" && t.path[1] === "size";
const round = (n: number) => Number(n.toFixed(4));

const transforms = {
  "kan/color": {
    type: "value" as const,
    filter: (t: TransformedToken) => t.$type === "color",
    transform: (t: TransformedToken) => {
      const { colorSpace, components, alpha } = t.$value as {
        colorSpace: string;
        components: number[];
        alpha?: number;
      };
      if (colorSpace !== "oklch")
        throw new Error(`${t.path.join(".")}: only oklch colors are supported, got ${colorSpace}`);
      return `oklch(${components.join(" ")}${alpha !== undefined && alpha !== 1 ? ` / ${alpha}` : ""})`;
    },
  },
  "kan/dimension": {
    type: "value" as const,
    filter: (t: TransformedToken) => t.$type === "dimension",
    transform: (t: TransformedToken) => {
      const { value, unit } = t.$value as Dimension;
      return unit === "px" && isRem(t) ? `${round(value / 16)}rem` : `${value}${unit}`;
    },
  },
  "kan/duration": {
    type: "value" as const,
    filter: (t: TransformedToken) => t.$type === "duration",
    transform: (t: TransformedToken) => `${(t.$value as Dimension).value}${(t.$value as Dimension).unit}`,
  },
  "kan/cubic-bezier": {
    type: "value" as const,
    filter: (t: TransformedToken) => t.$type === "cubicBezier",
    transform: (t: TransformedToken) => `cubic-bezier(${(t.$value as number[]).join(", ")})`,
  },
  "kan/font-family": {
    type: "value" as const,
    filter: (t: TransformedToken) => t.$type === "fontFamily",
    transform: (t: TransformedToken) =>
      ([] as string[])
        .concat(t.$value as string | string[])
        .map((f) => (GENERIC_FONTS.has(f) || /^[\w-]+$/.test(f) ? f : `"${f}"`))
        .join(", "),
  },
};

const dotted = (t: TransformedToken) => t.path.join(".");
const cssName = (t: TransformedToken) => `--${t.name}`;

function docsJson(tokens: TransformedToken[]): string {
  const rows = tokens.map((t) => ({
    name: dotted(t),
    cssVar: cssName(t),
    type: t.$type,
    value: t.$value,
    source: t.original.$value,
    ...(t.$description ? { description: t.$description } : {}),
  }));
  return `${JSON.stringify(rows, null, 2)}\n`;
}

function typedModule(tokens: TransformedToken[]): string {
  const lines = tokens.map(
    (t) =>
      `  ${JSON.stringify(dotted(t))}: { cssVar: ${JSON.stringify(cssName(t))}, type: ${JSON.stringify(t.$type)}, value: ${JSON.stringify(t.$value)} },`,
  );
  return [
    `// ${HEADER}`,
    "",
    "export const tokens = {",
    ...lines,
    "} as const;",
    "",
    '/** Every token\'s name, e.g. "color.cyan.500". */',
    "export type TokenName = keyof typeof tokens;",
    "",
    "/** var(--kan-…) for a token, for inline styles and CSS-in-JS. */",
    "export const cssVar = (name: TokenName): string => `var(${tokens[name].cssVar})`;",
    "",
  ].join("\n");
}

export async function buildTokens({ src, out }: { src: string; out: string }): Promise<string[]> {
  const { problems } = readTokens(src);
  if (problems.length) throw new Error(`invalid tokens:\n${problems.map((p) => `  ${p}`).join("\n")}`);

  const sd = new StyleDictionary({
    source: [path.join(src, "**/*.json")],
    usesDtcg: true,
    log: { verbosity: "verbose", warnings: "disabled", errors: { brokenReferences: "throw" } },
    hooks: {
      transforms,
      formats: {
        "kan/docs-json": ({ dictionary }) => docsJson(dictionary.allTokens),
        "kan/typed-module": ({ dictionary }) => typedModule(dictionary.allTokens),
      },
      fileHeaders: { kan: () => [HEADER] },
    },
    platforms: {
      web: {
        transforms: ["name/kebab", ...Object.keys(transforms)],
        prefix: PREFIX,
        buildPath: `${out.replace(/\/$/, "")}/`,
        files: [
          {
            destination: "tokens.css",
            format: "css/variables",
            options: { outputReferences: true, fileHeader: "kan" },
          },
          { destination: "tokens.ts", format: "kan/typed-module" },
          { destination: "tokens.json", format: "kan/docs-json" },
        ],
      },
    },
  });

  try {
    await sd.buildAllPlatforms();
  } catch (e) {
    const message = (e as Error).message;
    const refs = [...message.matchAll(/\{([^}]+)\} tries to reference \{([^}]+)\}, which is not defined/g)];
    if (refs.length) {
      throw new Error(
        `broken references:\n${refs.map(([, from, to]) => `  ${from} references ${to}, which doesn't exist`).join("\n")}`,
        { cause: e },
      );
    }
    throw e;
  }
  return ["tokens.css", "tokens.ts", "tokens.json"].map((f) => path.join(out, f));
}

if (import.meta.main) {
  const arg = (name: string, fallback: string) => {
    const i = process.argv.indexOf(name);
    return path.resolve(i > 0 ? process.argv[i + 1] : fallback);
  };
  const out = arg("--out", path.join(import.meta.dir, "dist"));
  fs.rmSync(path.join(out, "tokens.css"), { force: true });
  try {
    const files = await buildTokens({ src: arg("--src", path.join(import.meta.dir, "src")), out });
    console.log(`built ${files.map((f) => path.relative(process.cwd(), f)).join(", ")}`);
  } catch (e) {
    console.error(`tokens: ${(e as Error).message}`);
    process.exit(1);
  }
}
